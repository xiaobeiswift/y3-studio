use crate::env::{normalize_path, ProjectContext};
use sha2::{Digest, Sha256};
use std::fs;
use std::path::{Path, PathBuf};

pub const CLOUD_DEBUG_BEGIN_MARKER: &str = "-- BEGIN Y3 HELPER LOCAL CLOUD DEBUG";
pub const CLOUD_DEBUG_END_MARKER: &str = "-- END Y3 HELPER LOCAL CLOUD DEBUG";

/// 本地云脚本调试引导管理（对应原版 `src/cloudScript.ts` & `src/cloudScriptDebug.ts`）
pub struct CloudScriptManager;

impl CloudScriptManager {
    pub fn get_pipe_path(project_path: &Path) -> String {
        let norm = normalize_path(project_path)
            .to_string_lossy()
            .replace('\\', "/")
            .to_lowercase();
        let mut hasher = Sha256::new();
        hasher.update(norm.as_bytes());
        let h = hex::encode(hasher.finalize());
        format!(r"\\.\pipe\y3-helper-cloud-{}", &h[..24])
    }

    pub fn build_bootstrap_block(
        debugger_root: &Path,
        addr: &str,
        wait_debugger: bool,
        pipe_path: &str,
    ) -> String {
        let root_escaped = debugger_root.to_string_lossy().replace('\\', "/");
        let pipe_escaped = pipe_path.replace('\\', "\\\\");
        format!(
            "{begin}\n-- Auto-generated by Y3 Helper. Safe to delete when local cloud debug is disabled.\ndo\n    local ok, dbg = pcall(dofile, \"{root}/script/debugger.lua\")\n    if ok and dbg then\n        dbg:io(\"listen:{addr}\")\n        if {wait} then\n            dbg:wait()\n        end\n        dbg:start()\n    end\n    local pipe_path = \"{pipe}\"\n    local _ = pipe_path\nend\n{end}\n",
            begin = CLOUD_DEBUG_BEGIN_MARKER,
            root = root_escaped,
            addr = addr,
            wait = if wait_debugger { "true" } else { "false" },
            pipe = pipe_escaped,
            end = CLOUD_DEBUG_END_MARKER,
        )
    }

    /// 幂等更新或移除 `cloud_script/main.lua` 头部的本地云脚本调试引导块
    pub fn sync_cloud_script(
        project: &ProjectContext,
        enable: bool,
        debugger_root: Option<&Path>,
        addr: Option<&str>,
        wait_debugger: bool,
    ) -> anyhow::Result<Option<PathBuf>> {
        let main_lua = project.project_path.join("cloud_script/main.lua");
        if !main_lua.is_file() {
            return Ok(None);
        }
        let original = fs::read_to_string(&main_lua)?;
        let stripped = Self::strip_bootstrap(&original);

        if !enable {
            if stripped != original {
                fs::write(&main_lua, stripped)?;
            }
            return Ok(Some(main_lua));
        }

        let dbg_root = debugger_root.unwrap_or(&project.project_path);
        let listen_addr = addr.unwrap_or("127.0.0.1:12396");
        let pipe_path = Self::get_pipe_path(&project.project_path);
        let block = Self::build_bootstrap_block(dbg_root, listen_addr, wait_debugger, &pipe_path);
        let updated = if stripped.is_empty() {
            block
        } else {
            format!("{}\n{}", block.trim_end(), stripped)
        };
        fs::write(&main_lua, updated)?;
        Ok(Some(main_lua))
    }

    pub fn strip_bootstrap(content: &str) -> String {
        if let (Some(start), Some(end)) = (
            content.find(CLOUD_DEBUG_BEGIN_MARKER),
            content.find(CLOUD_DEBUG_END_MARKER),
        ) {
            if end > start {
                let after_end = end + CLOUD_DEBUG_END_MARKER.len();
                let before = &content[..start];
                let after = content[after_end..].trim_start_matches(['\r', '\n']);
                return format!("{}{}", before, after);
            }
        }
        content.to_string()
    }
}
